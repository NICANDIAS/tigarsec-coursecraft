"""
Compares the database schema SQLAlchemy's models expect against what actually exists in
the live database, and can fix any gap automatically - this replaces the recurring "run
this ALTER TABLE command from the script footer" pattern, which kept getting missed.

Purely additive: only ever CREATEs a missing table or ADDs a missing column, never drops
or modifies anything that already exists - there's no real risk to running the fix, worst
case it's a no-op (everything already matches).
"""
from sqlalchemy import text

SQLITE_TYPE_MAP = {
    "Integer": "INTEGER",
    "Float": "REAL",
    "Boolean": "BOOLEAN",
    "Text": "TEXT",
    "JSON": "TEXT",  # SQLite has no native JSON type - stored as text, same as every prior migration
    "DateTime": "DATETIME",
    "Date": "DATE",
}


def _sqlite_type_for(sa_type) -> str:
    type_name = type(sa_type).__name__
    if type_name == "String":
        length = getattr(sa_type, "length", None)
        return f"VARCHAR({length})" if length else "VARCHAR"
    return SQLITE_TYPE_MAP.get(type_name, "TEXT")  # unknown type - fall back to TEXT rather than crash


def _sqlite_default_clause(col) -> str:
    """
    A literal SQL DEFAULT clause for a column, if it has a simple, literal Python-side
    default declared (a plain number, string, or boolean) - confirmed as a real, live bug
    without this: a bare ALTER TABLE ADD COLUMN leaves every EXISTING row NULL for the new
    column regardless of what default the model itself declares, which silently disabled a
    real feature (a None value read by application code as "not configured" rather than
    the intended default value).

    Only handles simple, literal defaults - anything more complex (a callable, a function
    reference) is skipped, leaving existing rows NULL as before rather than risk
    generating invalid SQL from something that can't be expressed as a literal. Wrapped
    defensively since this touches the underlying SQLAlchemy Column API directly - any
    unexpected shape here falls back to no default clause (the pre-existing behavior)
    rather than breaking schema sync entirely.
    """
    try:
        default = getattr(col, "default", None)
        if default is None or not hasattr(default, "arg"):
            return ""
        value = default.arg
        if callable(value):
            return ""
        if isinstance(value, bool):
            return f" DEFAULT {1 if value else 0}"
        if isinstance(value, (int, float)):
            return f" DEFAULT {value}"
        if isinstance(value, str):
            escaped = value.replace("'", "''")
            return f" DEFAULT '{escaped}'"
        return ""
    except Exception:
        return ""


def diff_schema(engine, Base) -> dict:
    """Returns {"missing_tables": [...], "missing_columns": {table: [(col, type), ...]}}"""
    with engine.connect() as conn:
        existing_tables = {
            row[0] for row in conn.execute(text("SELECT name FROM sqlite_master WHERE type='table'"))
        }
        missing_tables = []
        missing_columns = {}
        for table_name, table in Base.metadata.tables.items():
            if table_name not in existing_tables:
                missing_tables.append(table_name)
                continue
            actual_columns = {
                row[1] for row in conn.execute(text(f"PRAGMA table_info({table_name})"))
            }
            missing = [
                (col.name, _sqlite_type_for(col.type) + _sqlite_default_clause(col))
                for col in table.columns if col.name not in actual_columns
            ]
            if missing:
                missing_columns[table_name] = missing
    return {"missing_tables": missing_tables, "missing_columns": missing_columns}


def apply_schema_fix(engine, Base, diff: dict) -> list:
    """
    Applies whatever the diff found - creates missing tables via SQLAlchemy's own
    metadata (so the actual CREATE TABLE SQL is generated by SQLAlchemy itself, proven
    correct by construction, never hand-written), and adds missing columns via direct
    ALTER TABLE. Returns a list of what was actually done, so the result is genuinely
    verifiable rather than just "trust me it worked."
    """
    report = []
    if diff["missing_tables"]:
        tables_to_create = [Base.metadata.tables[name] for name in diff["missing_tables"]]
        Base.metadata.create_all(bind=engine, tables=tables_to_create)
        for name in diff["missing_tables"]:
            report.append(f"Created table: {name}")

    if diff["missing_columns"]:
        with engine.begin() as conn:
            for table_name, columns in diff["missing_columns"].items():
                for col_name, col_type in columns:
                    try:
                        conn.execute(text(f"ALTER TABLE {table_name} ADD COLUMN {col_name} {col_type}"))
                        report.append(f"Added column: {table_name}.{col_name} ({col_type})")
                    except Exception as e:
                        report.append(f"FAILED: {table_name}.{col_name} - {e}")
    return report
